/**
 * @file mr/raster/line.hpp
 * @brief Bresenham 画线（1962）
 *
 * ## 它解决的问题
 *
 * 屏幕是整数网格，直线是连续的。给定两个整数端点，要选出一串像素，
 * 使它们"看起来像"那条直线。
 *
 * 朴素做法是沿 x 走一步、算 `y = y0 + (x - x0) * dy / dx`、四舍五入。
 * 正确，但每个像素一次除法。1962 年 IBM 的 Jack Bresenham 在给绘图仪
 * 写控制程序时发现：**你根本不需要知道 y 是多少，只需要知道
 * "该不该往上走一格"。** 而那个判断可以用一个整数累加器维护，
 * 每步只做加减法。
 *
 * 这是计算机图形学里最早、也最能说明问题的一个例子：
 * 把"求值"换成"增量判定"。后面的深度插值、纹理坐标插值、
 * 扫描线填充，用的都是同一个思路。
 *
 * ## 判别式怎么来的
 *
 * 先看第一象限、斜率在 0~1 之间的情况（`dx >= dy >= 0`）。
 * 每一步 x 必然 +1，问题只是 y 要不要 +1。
 *
 * 设当前像素中心到真实直线的垂直偏差为 `e`。走一步 x，真实的 y
 * 增加 `dy/dx`，所以 `e += dy/dx`。当 `e >= 1/2` 时，
 * 上面那个像素更近，于是 `y += 1` 且 `e -= 1`。
 *
 * `dy/dx` 和 `1/2` 都是分数 —— 但只要两边同乘 `2*dx`（正数，不改变
 * 不等号方向），全部变成整数：
 *
 *   `e >= 1/2`  ⟺  `2*dx*e >= dx`
 *   `e += dy/dx` ⟺  `(2*dx*e) += 2*dy`
 *
 * 令 `err = 2*dx*e`，整个判定只剩整数加减和一次比较。
 * **除法和浮点从此消失，而且是精确的，不是近似的** ——
 * 这条线上没有任何舍入误差可以累积。
 *
 * ## 八个卦限
 *
 * 上面只对一个卦限成立。教科书常见的做法是"交换 x/y、取反符号"
 * 把另外七种情况映射回来，写出来是一堆 if。
 *
 * 本实现用的是**对称形式**：同时维护 x 和 y 两个方向的判别式，
 * 每步各自决定要不要走。它天然覆盖八个卦限，没有任何分类讨论，
 * 代价是每步多一次比较、一次移位。
 *
 * 换来的不只是短：**没有分支表就没有"某个卦限漏了"这类 bug**。
 * 而那正是这个算法最经典的错误形态 —— 七个方向都对，第八个差一格，
 * 而且只在特定斜率下出现。`tests/` 里有专门覆盖八个卦限的用例。
 *
 * ## 关于"抗锯齿的前身"
 *
 * Bresenham 的输出是**硬边**的：每个 x 只点一个像素，非黑即白。
 * 放大看是阶梯。1991 年 Xiaolin Wu 的算法在同一个增量框架上，
 * 把误差项 `err` 直接当作**覆盖率**用，同时点上下两个像素、
 * 按误差分配亮度 —— 那就是抗锯齿版本，是本项目的下一课。
 *
 * 所以这两节课的关系不是"简单版和高级版"，而是同一个判别式的
 * 两种读法：一个拿它做决策，一个拿它做权重。
 *
 * ## 裁剪
 *
 * 端点可以在屏幕外。本实现的做法是**逐像素做边界检查**
 * （`Surface::put()` 越界即丢弃），外加一个整数 outcode 平凡拒绝。
 *
 * 这是正确的，但对一条从 (-10^6, 0) 到 (10^6, 0) 的线仍然要走
 * 两百万步。正确的解法是先做 Cohen–Sutherland 裁剪再光栅化，
 * 那是后面的课。
 *
 * **而且那两者的结果未必逐像素相同** —— 裁剪把端点挪到边界上，
 * 判别式的初值随之改变，靠近边界的几个像素可能选得不一样。
 * 这不是 bug，是"先裁剪"与"后裁剪"两种流水线的固有差异，
 * 在做增量式裁剪时必须知道。
 */
#pragma once

#include <cstdint>
#include <type_traits>

#include "mr/bug.hpp"

#include "mr/surface.hpp"

namespace mr::raster {

struct Point {
    int32_t x = 0;
    int32_t y = 0;
};

/**
 * @brief 画一条从 `a` 到 `b` 的线
 *
 * 端点都会被画上（闭区间）。`a == b` 时画一个像素。
 * 越界部分静默丢弃。
 *
 * **只用整数加减和一次移位**，没有乘除，没有浮点。
 */
void draw_line(const Surface& surface, Point a, Point b, Pixel color) noexcept;

/**
 * @brief 同上，但把像素交给回调而不是写进 surface
 *
 * 存在的理由是**可测性**：单测要检查的是"选出了哪一串像素"，
 * 而不是"某块内存变成了什么"。有了这个入口，
 * 连通性、对称性、端点、卦限覆盖这些性质都能直接断言。
 *
 * 回调**不做**边界检查，坐标可能是负的或超出任何 surface ——
 * 这里返回的是算法本身的输出，裁剪是调用方的事。
 *
 * ## 提前结束
 *
 * `plot` 可以返回 `bool`：返回 false 就停。返回 `void` 的话一路画到底，
 * 两种签名都支持，编译期分派，没有运行期代价。
 *
 * 加这个入口的直接原因是测试：判别式写错的一种常见形态是**终止条件
 * 永远不成立**（某个方向的步进符号取反就会这样），此时循环不返回。
 * 一个挂死的测试比一个失败的测试难查得多 —— 没有输出、没有退出码，
 * 在 CI 里只表现为超时。有了提前结束，测试可以设一个步数上限，
 * 把"死循环"这种失败模式变成一条明确的 FAIL。
 *
 * 它也不只对测试有用：后面做遮挡查询、光线步进时，
 * "找到第一个命中就停"是常见需求。
 *
 * ## 循环有硬上限，这不是防御性编程
 *
 * 正确的实现走的步数**正好**是 `max(|dx|, |dy|) + 1` ——
 * 这不是一个经验值或者安全余量，是这个算法的定义决定的确切步数。
 * 所以把它作为循环上限，对正确的实现没有任何影响。
 *
 * 加它的理由来自实测：往这个循环里注入五种典型的判别式错误，
 * **有两种不会画错，而是根本不返回**（终止条件永远不成立）。
 * 一个挂死的进程比一个画错的画面难查得多 —— 它没有输出、
 * 没有退出码，在 CI 里只表现为超时。
 *
 * 上限一旦触发，就说明更新规则写错了。`MR_DEBUG` 下会 abort 并说明，
 * 不是静静地画短一截 —— 那属于把 bug 掩盖成"看起来只是短了点"。
 *
 * @param plot 每个像素调一次，按从 `a` 到 `b` 的顺序。
 *             返回 bool 时，false 表示停止。
 */
template <typename PlotFn>
void trace_line(Point a, Point b, PlotFn&& plot) noexcept {
    // dx 取正、dy 取负，是为了让下面两个判定都写成同一种形式
    // （`e2 >= dy` 与 `e2 <= dx`），不用为符号再分情况。
    const int32_t dx = a.x < b.x ? b.x - a.x : a.x - b.x;
    const int32_t dy = a.y < b.y ? a.y - b.y : b.y - a.y;  // <= 0
    const int32_t sx = a.x < b.x ? 1 : -1;
    const int32_t sy = a.y < b.y ? 1 : -1;

    int32_t err = dx + dy;

    // 正确实现的确切步数。见上面的说明：这是定义值，不是安全余量。
    int32_t budget = (dx > -dy ? dx : -dy) + 1;

    for (;;) {
        if constexpr (std::is_invocable_r_v<bool, PlotFn&, int32_t, int32_t>) {
            if (! plot(a.x, a.y)) {
                return;
            }
        } else {
            plot(a.x, a.y);
        }

        if (a.x == b.x && a.y == b.y) {
            break;
        }
        if (--budget <= 0) {
            // 只可能由更新规则错误引起。
            MR_BUG("trace_line exceeded its exact step budget: the update rule is wrong");
            return;
        }

        // 唯一的乘法，而且是乘 2 —— 移位。写成 `err << 1` 会在 err 为负时
        // 触发有符号左移的实现定义行为，所以写 `err * 2`：
        // 编译器一样生成一条 shift/lea，语义却是明确的。
        const int32_t e2 = err * 2;

        // 两个判定必须都用**进入本轮时**的 e2，不能用更新过的 err。
        // 写成两个连续的 if 并在第一个里改 err，会在 45 度线上少走一格 ——
        // 这是这个形式最经典的写错方式，症状只在 |dx| == |dy| 时出现。
        if (e2 >= dy) {
            err += dy;
            a.x += sx;
        }
        if (e2 <= dx) {
            err += dx;
            a.y += sy;
        }
    }
}

} // namespace mr::raster
